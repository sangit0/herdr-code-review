import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdtempSync,writeFileSync,readFileSync,rmSync,mkdirSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
const B=await import('../mods/tabbed-changes/branches.js').catch(()=>({}));
assert.equal(typeof B.listBranches,'function');
const root=mkdtempSync(join(tmpdir(),'herdr-branches-')),repo=join(root,'repo'),remote=join(root,'remote.git');mkdirSync(repo);
const run=(args,cwd=repo)=>execFileSync('git',args,{cwd,encoding:'utf8',stdio:['ignore','pipe','pipe']});
const git=async args=>run(args);
try {
 run(['init','--bare',remote],root);run(['init','-b','main']);run(['config','user.name','Test']);run(['config','user.email','test@example.invalid']);
 writeFileSync(join(repo,'file.txt'),'base\n');run(['add','.']);run(['commit','-m','base']);run(['remote','add','origin',remote]);
 await B.pushCurrent(git,'main');assert.equal(run(['config','branch.main.remote']).trim(),'origin');
 run(['switch','-c','feature']);writeFileSync(join(repo,'file.txt'),'feature\n');run(['commit','-am','feature']);
 const feature=run(['rev-parse','HEAD']).trim();
 run(['update-ref','refs/remotes/origin/remote-only',feature]);
 run(['symbolic-ref','refs/remotes/origin/HEAD','refs/remotes/origin/main']);
 let branches=await B.listBranches(git);
 assert.ok(branches.find(b=>b.name==='main'&&b.kind==='local'));
 assert.ok(branches.find(b=>b.name==='feature'&&b.current));
 assert.ok(branches.find(b=>b.name==='origin/remote-only'&&b.kind==='remote'));
 assert.ok(!branches.some(b=>b.name==='origin/HEAD'));
 const expected=await B.currentBranch(git);
 await B.switchBranch(git,branches.find(b=>b.name==='main'),expected);
 assert.equal(run(['branch','--show-current']).trim(),'main');
 await assert.rejects(()=>B.switchBranch(git,branches.find(b=>b.name==='feature'),expected),/changed/i);
 await B.switchBranch(git,branches.find(b=>b.name==='origin/remote-only'),await B.currentBranch(git));
 assert.equal(run(['branch','--show-current']).trim(),'remote-only');assert.equal(run(['config','branch.remote-only.merge']).trim(),'refs/heads/remote-only');
 await B.switchBranch(git,(await B.listBranches(git)).find(b=>b.name==='main'),await B.currentBranch(git));
 writeFileSync(join(repo,'file.txt'),'unsaved\n');
 await assert.rejects(async()=>B.switchBranch(git,(await B.listBranches(git)).find(b=>b.name==='feature'),await B.currentBranch(git)));
 assert.equal(readFileSync(join(repo,'file.txt'),'utf8'),'unsaved\n');assert.equal(run(['branch','--show-current']).trim(),'main');
 writeFileSync(join(repo,'file.txt'),'base\n');run(['switch','feature']);
 // A misleading push.default must not push the current branch to main.
 run(['config','push.default','matching']);run(['config','push.followTags','true']);run(['tag','-a','private-test-tag','-m','must stay local']);await B.pushCurrent(git,'feature');
 assert.equal(run(['rev-parse','refs/heads/feature'],remote).trim(),feature);
 assert.notEqual(run(['rev-parse','refs/heads/main'],remote).trim(),feature);
 await assert.rejects(()=>B.pushCurrent(git,'main'),/changed/i);
 assert.throws(()=>run(['rev-parse','--verify','refs/tags/private-test-tag'],remote));
 run(['config','branch.feature.merge','refs/heads/review-destination']);
 await B.pushCurrent(git,'feature');assert.equal(run(['rev-parse','refs/heads/review-destination'],remote).trim(),feature);
 await assert.rejects(()=>B.pushCurrent(git,{name:'feature',upstream:'origin/feature'}),/upstream/i);
 assert.equal(typeof B.pullCurrent,'function');
 await assert.rejects(()=>B.pullCurrent(git,{name:'main',upstream:'origin/main'}),/changed/i);
 await assert.rejects(()=>B.pullCurrent(git,{name:'feature',upstream:'origin/feature'}),/upstream/i);
 await B.pullCurrent(git,{name:'feature',upstream:'origin/review-destination'});
 const other=join(root,'other-worktree');run(['worktree','add','-b','occupied',other]);
 const occupied=(await B.listBranches(git)).find(b=>b.name==='occupied');assert.ok(occupied.worktree);
 await assert.rejects(async()=>B.switchBranch(git,occupied,await B.currentBranch(git)),/worktree/);
 run(['switch','--detach','HEAD']);await assert.rejects(()=>B.pushCurrent(git,null),/branch/i);
} finally {rmSync(root,{recursive:true,force:true});}
console.log('branch switching and upstream push ok');
