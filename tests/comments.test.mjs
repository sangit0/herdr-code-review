import assert from 'node:assert/strict';
const C = await import('../mods/tabbed-changes/comment-model.js').catch(() => ({}));
assert.equal(typeof C.contextForRow, 'function', 'line context helper is required');
const source = {root:'/repo',on:null};
assert.deepEqual(C.contextForRow({path:'a.js',kind:'-',old:8,text:'old'}, source), {source,path:'a.js',line:8,side:'old',code:'old'});
assert.equal(C.contextForRow({path:'a.js',kind:'@',text:'hunk'},source), null);
assert.equal(C.contextForRow({path:'a.js',kind:'c',l:{n:2,text:'before'},r:{n:3,text:'after'}},source,'old').line,2);
assert.equal(C.contextForRow({path:'a.js',kind:'c',l:{n:2,text:'before'},r:null},source,'new'),null);
const context=C.contextForRow({path:'a.js',kind:'+',next:9,text:'new'},source);
assert.throws(()=>C.makeComment(context,'  ','1'),/comment/i);
const note=C.makeComment(context,'Please simplify','1');
assert.equal(note.text,'Please simplify');
assert.equal(C.forSource([note,{...note,id:'2',source:{root:'/repo',on:'remote'}}],source).length,1);
assert.match(C.formatComments([note]),/a.js:9 \(new\)/);
assert.match(C.formatComments([note]),/Please simplify/);
assert.match(C.formatComments([note]),/new/);
let calls=[];
const target={address:'t1',space:'s1',status:'idle'};
await C.deliverComments({notes:[note],target:'t1',space:'s1',agents:[target],send:async args=>{calls.push(args);return {code:0};}});
assert.deepEqual(calls[0].slice(0,4),['send','--if','idle','t1']);
await assert.rejects(()=>C.deliverComments({notes:[note],target:'t1',space:'s1',agents:[{...target,status:'working'}],send:async()=>assert.fail()}),/idle/i);
await assert.rejects(()=>C.deliverComments({notes:[note],target:'t1',space:'s2',agents:[target],send:async()=>assert.fail()}),/agent/i);
await assert.rejects(()=>C.deliverComments({notes:[note],target:'t1',space:'s1',agents:[target],send:async()=>({code:1,stderr:'offline'})}),/offline/);
console.log('comments ok');
assert.equal(typeof C.forLine,'function','comments must be attached to individual lines');
assert.equal(C.forLine([note,{...note,id:'2',line:10}],context).length,1);
assert.equal(C.forLine([note,{...note,id:'3',side:'old'}],context).length,1);
assert.equal(C.forLine([note],{...context,source:{root:'/other',on:null}}).length,0);
console.log('per-line comments ok');
assert.equal(typeof C.findMatchingRow,'function');
const refreshed={path:'a.js',kind:'+',next:9,text:'new'};
assert.equal(C.findMatchingRow([refreshed],context),refreshed);
assert.equal(C.findMatchingRow([{...refreshed,next:10}],context),null);
assert.equal(C.findMatchingRow([{...refreshed,text:'changed'}],context),null);
