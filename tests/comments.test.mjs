import assert from 'node:assert/strict';
const C = await import('../mods/tabbed-changes/comment-model.js').catch(() => ({}));
assert.equal(typeof C.contextForRow, 'function', 'line context helper is required');
const source = {root:'/repo',on:null};
assert.deepEqual(C.contextForRow({path:'a.js',kind:'-',old:8,text:'old'}, source), {source,path:'a.js',line:8,side:'old',code:'old'});
assert.equal(C.contextForRow({path:'a.js',kind:'@',text:'hunk'},source), null);
assert.equal(C.contextForRow({path:'a.js',kind:'c',l:{n:2,text:'before'},r:{n:3,text:'after'}},source,'old').line,2);
assert.equal(C.contextForRow({path:'a.js',kind:'c',l:{n:2,text:'before'},r:null},source,'new'),null);
const context=C.contextForRow({path:'a.js',kind:'+',next:9,text:'new'},source);
assert.throws(()=>C.makeComment(context,'  ','1'),/comment/i);
const note=C.makeComment(context,'Please simplify','1');
assert.equal(note.text,'Please simplify');
assert.equal(C.forSource([note,{...note,id:'2',source:{root:'/repo',on:'remote'}}],source).length,1);
assert.match(C.formatComments([note]),/a.js:9 \(new\)/);
assert.match(C.formatComments([note]),/Please simplify/);
assert.match(C.formatComments([note]),/new/);
let calls=[];
const target={address:'t1',space:'s1',status:'idle'};
await C.deliverComments({notes:[note],target:'t1',space:'s1',agents:[target],send:async args=>{calls.push(args);return {code:0};}});
assert.deepEqual(calls[0].slice(0,4),['send','--if','idle','t1']);
await assert.rejects(()=>C.deliverComments({notes:[note],target:'t1',space:'s1',agents:[{...target,status:'working'}],send:async()=>assert.fail()}),/idle/i);
await assert.rejects(()=>C.deliverComments({notes:[note],target:'t1',space:'s2',agents:[target],send:async()=>assert.fail()}),/agent/i);
await assert.rejects(()=>C.deliverComments({notes:[note],target:'t1',space:'s1',agents:[target],send:async()=>({code:1,stderr:'offline'})}),/offline/);
console.log('comments ok');
assert.equal(typeof C.forLine,'function','comments must be attached to individual lines');
assert.equal(C.forLine([note,{...note,id:'2',line:10}],context).length,1);
assert.equal(C.forLine([note,{...note,id:'3',side:'old'}],context).length,1);
assert.equal(C.forLine([note],{...context,source:{root:'/other',on:null}}).length,0);
console.log('per-line comments ok');
assert.equal(typeof C.findMatchingRow,'function');
const refreshed={path:'a.js',kind:'+',next:9,text:'new'};
assert.equal(C.findMatchingRow([refreshed],context),refreshed);
assert.equal(C.findMatchingRow([{...refreshed,next:10}],context),null);
assert.equal(C.findMatchingRow([{...refreshed,text:'changed'}],context),null);
// Range selection preserves source/side, supports reverse selection, and rejects hidden gaps.
assert.equal(typeof C.rangeContext,'function');
const line9=context, line10={...context,line:10,code:'second'};
const range=C.rangeContext(line10,line9,[line9,line10]);
assert.equal(range.line,9); assert.equal(range.endLine,10); assert.equal(range.code,'new\nsecond');
assert.equal(C.rangeContext(line9,{...line10,path:'other'},[line9,line10]),null);
assert.equal(C.rangeContext(line9,{...line10,line:11},[line9,line10]),null);
assert.match(C.formatComments([C.makeComment(range,'range note','range')]),/a.js:9-10/);
assert.equal(typeof C.isOutdated,'function');
assert.equal(C.isOutdated({...note,endLine:10,code:'new\nsecond'},[line9,line10]),false);
assert.equal(C.isOutdated({...note,endLine:10,code:'new\nsecond'},[line9,{...line10,code:'edited'}]),true);
assert.equal(C.isOutdated(note,[]),true);
assert.equal(typeof C.sendAndRemove,'function');
let saved=[note,{...note,id:'other'}];
await C.sendAndRemove({note,target:'t1',space:'s1',agents:[target],send:async()=>({code:0}),read:()=>saved,write:next=>saved=next});
assert.deepEqual(saved.map(n=>n.id),['other']);
saved=[note];
await assert.rejects(()=>C.sendAndRemove({note,target:'t1',space:'s1',agents:[target],send:async()=>({code:1,stderr:'failed'}),read:()=>saved,write:next=>saved=next}),/failed/);
assert.equal(saved.length,1);
console.log('range, outdated and removal ok');
assert.equal(typeof C.selectionForRows,'function');
assert.equal(C.selectionForRows([refreshed],context,{root:'/other',on:null},'new'),null);
assert.equal(C.selectionForRows([refreshed],context,{root:'/repo',on:'remote'},'new'),null);
assert.equal(C.selectionForRows([refreshed],context,source,'new').code,'new');
assert.equal(C.rangeContext(line9,{...line10,side:'old'},[line9,line10]),null);
assert.equal(C.rangeContext(line9,{...line10,source:{root:'/repo',on:'remote'}},[line9,line10]),null);
assert.equal(C.rangeContext(line9,{...line10,line:509},[line9,line10]),null);
const rangeNote=C.makeComment(range,'range note','range');
assert.equal(C.forLine([rangeNote],line10).length,1,'gutter badge covers each line in a range');
saved=[note];
await C.sendAndRemove({note,target:'t1',space:'s1',agents:[target],send:async()=>{saved.push({...note,id:'added-during-send'});return {code:0};},read:()=>saved,write:next=>saved=next});
assert.deepEqual(saved.map(n=>n.id),['added-during-send']);
const oldBaseA=C.contextForRow({kind:'-',old:3,path:'a.js',text:'before',baseRevision:'a'.repeat(40),baseLabel:'origin/main'},source);
const oldBaseB=C.contextForRow({kind:'-',old:3,path:'a.js',text:'before',baseRevision:'b'.repeat(40),baseLabel:'origin/master'},source);
assert.notEqual(oldBaseA.revision,oldBaseB.revision,'old-side comments must retain their baseline');
assert.equal(C.forLine([C.makeComment(oldBaseA,'baseline note','old')],oldBaseB).length,0);
const fetchedBase={...oldBaseA,revision:'c'.repeat(40),code:'after fetch'};
assert.equal(C.forLine([C.makeComment(oldBaseA,'pending','pending')],fetchedBase).length,1,'fetching the same base keeps pending comments visible');
assert.equal(C.isOutdated(C.makeComment(oldBaseA,'pending','pending'),[fetchedBase]),true);
